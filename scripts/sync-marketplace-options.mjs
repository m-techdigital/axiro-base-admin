import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contract = JSON.parse(
    fs.readFileSync(
        path.join(root, 'src/contracts/marketplace-contract.json'),
        'utf8',
    ),
)
const catalog = contract.option_catalog || {}
const quote = (value) => `'${String(value ?? '').replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const options = (items = []) =>
    `[\n${items
        .map(
            (item) =>
                `    {\n        value: ${quote(item.value)},\n        label: ${quote(item.label)},\n    },`,
        )
        .join('\n')}\n]`
const output = `// Generated by scripts/sync-marketplace-options.mjs. Do not edit manually.
export const MARKETPLACE_OPTIONS_CONTRACT_VERSION = ${quote(contract.contract_version)}
export const MARKETPLACE_OPTIONS_VERSION = ${quote(catalog.version)}
export const MARKETPLACE_OPTIONS_CACHE_TTL_SECONDS = ${Number(catalog.cache_ttl_seconds || 300)}
export const MARKETPLACE_DOCUMENT_TYPES = ${options(catalog.document_types)}
export const MARKETPLACE_DISPUTE_OUTCOMES = ${options(catalog.dispute_outcomes)}
`
const target = path.join(root, 'src/generated/marketplaceOptions.js')
if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
    if (current !== output) {
        console.error('marketplace options generated fallback is stale')
        process.exit(1)
    }
    console.log('marketplace options generated fallback is current')
} else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, output)
    console.log('generated', path.relative(root, target))
}
